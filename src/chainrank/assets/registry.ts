/**
 * Central 3D Asset Registry Manager Singleton
 */
export class ChainRankAssetRegistry {
  private assetsMap: Map<string, ChainRankAsset> = new Map();

  constructor(initialAssets: ChainRankAsset[] = chainRankAssetCollection) {
    initialAssets.forEach((asset) => this.assetsMap.set(asset.id, asset));
  }

  public registerAsset(asset: ChainRankAsset): void {
    this.assetsMap.set(asset.id, asset);
  }

  public getAsset(id: string): ChainRankAsset | undefined {
    return this.assetsMap.get(id);
  }

  public getAllAssets(): ChainRankAsset[] {
    return Array.from(this.assetsMap.values());
  }

  public getAssetsByCategory(category: ChainRankAssetCategory): ChainRankAsset[] {
    return this.getAllAssets().filter((a) => a.category === category);
  }

  public getValidAssets(): ChainRankAsset[] {
    return this.getAllAssets().filter((a) => a.validationStatus !== 'INVALID_ASSET');
  }

  public filterAssets(options: AssetFilterOptions): ChainRankAsset[] {
    return this.getAllAssets().filter((asset) => {
      if (options.category && options.category !== 'all' && asset.category !== options.category) {
        return false;
      }
      if (options.format && options.format !== 'all' && asset.format !== options.format) {
        return false;
      }
      if (options.license && asset.license !== options.license) {
        return false;
      }
      if (options.validationStatus && options.validationStatus !== 'all' && asset.validationStatus !== options.validationStatus) {
        return false;
      }
      if (options.interactiveOnly && !asset.interactive) {
        return false;
      }
      if (options.searchQuery && options.searchQuery.trim() !== '') {
        const q = options.searchQuery.toLowerCase();
        const matchesName = asset.name.toLowerCase().includes(q);
        const matchesRole = asset.investigationRole.toLowerCase().includes(q);
        const matchesTags = asset.tags.some((t) => t.toLowerCase().includes(q));
        const matchesDesc = asset.description.toLowerCase().includes(q);
        if (!matchesName && !matchesRole && !matchesTags && !matchesDesc) {
          return false;
        }
      }
      return true;
    });
  }

  public getStats() {
    const all = this.getAllAssets();
    const procedural = all.filter((a) => a.format === 'procedural').length;
    const glb = all.filter((a) => a.format === 'glb').length;
    const valid = all.filter((a) => a.validationStatus === 'VALID' || a.validationStatus === 'PROCEDURAL').length;
    const invalid = all.filter((a) => a.validationStatus === 'INVALID_ASSET').length;
    const reviewRequired = all.filter((a) => a.validationStatus === 'REVIEW_REQUIRED').length;
    const byCategory: Record<string, number> = {};
    all.forEach((a) => {
      byCategory[a.category] = (byCategory[a.category] || 0) + 1;
    });

    return {
      total: all.length,
      procedural,
      glb,
      valid,
      invalid,
      reviewRequired,
      byCategory
    };
  }
}

// Global Singleton Instance
export const chainRankRegistry = new ChainRankAssetRegistry();